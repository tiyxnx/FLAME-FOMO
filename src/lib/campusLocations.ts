// Dijkstra Shortest Path Pedestrian Routing Algorithm
// -------------------------------------------------------------
interface ShortestPathResult {
  totalMeters: number;
  hubs: string[];
  notes: string[];
}

export function findShortestPedestrianPath(startHubId: string, endHubId: string): ShortestPathResult {
  if (startHubId === endHubId) {
    return { totalMeters: 0, hubs: [startHubId], notes: [] };
  }

  // Build bidirectional adjacency map
  const adj: Record<string, { node: string; weight: number; note: string }[]> = {};
  Object.keys(CAMPUS_HUB_NODES).forEach((id) => {
    adj[id] = [];
  });

  CAMPUS_EDGES.forEach((edge) => {
    if (adj[edge.u] && adj[edge.v]) {
      adj[edge.u].push({ node: edge.v, weight: edge.meters, note: edge.note });
      adj[edge.v].push({ node: edge.u, weight: edge.meters, note: edge.note });
    }
  });

  const distances: Record<string, number> = {};
  const previous: Record<string, { node: string; note: string } | null> = {};
  const unvisited = new Set<string>();

  Object.keys(CAMPUS_HUB_NODES).forEach((id) => {
    distances[id] = Infinity;
    previous[id] = null;
    unvisited.add(id);
  });

  distances[startHubId] = 0;

  while (unvisited.size > 0) {
    // Find unvisited node with smallest distance
    let current: string | null = null;
    let smallestDist = Infinity;
    unvisited.forEach((node) => {
      if (distances[node] < smallestDist) {
        smallestDist = distances[node];
        current = node;
      }
    });

    if (current === null || distances[current] === Infinity) {
      break;
    }

    if (current === endHubId) {
      break;
    }

    unvisited.delete(current);

    const neighbors = adj[current] || [];
    for (const neighbor of neighbors) {
      if (unvisited.has(neighbor.node)) {
        const alt = distances[current] + neighbor.weight;
        if (alt < distances[neighbor.node]) {
          distances[neighbor.node] = alt;
          previous[neighbor.node] = { node: current, note: neighbor.note };
        }
      }
    }
  }

  // Reconstruct path
  const pathHubs: string[] = [];
  const pathNotes: string[] = [];
  let curr: string | null = endHubId;

  while (curr && previous[curr]) {
    pathHubs.unshift(curr);
    const prevEntry: { node: string; note: string } | null = previous[curr];
    if (prevEntry) {
      pathNotes.unshift(prevEntry.note);
      curr = prevEntry.node;
    } else {
      break;
    }
  }

  if (curr) {
    pathHubs.unshift(curr);
  }

  return {
    totalMeters: distances[endHubId] !== Infinity ? distances[endHubId] : 150,
    hubs: pathHubs.length > 0 ? pathHubs : [startHubId, endHubId],
    notes: pathNotes,
  };
}

// -------------------------------------------------------------
// Calculate Full Campus Route between two venues
// -------------------------------------------------------------
export function calculateCampusRoute(fromId: string, toId: string): CampusRouteResult | null {
  const from = ALL_CAMPUS_LOCATIONS.find((l) => l.id === fromId);
  const to = ALL_CAMPUS_LOCATIONS.find((l) => l.id === toId);

  if (!from || !to) return null;

  // Same location
  if (from.id === to.id) {
    return {
      fromLocation: from,
      toLocation: to,
      distanceMeters: 0,
      walkTimeMinutes: 0,
      stepsCount: 0,
      paceDescription: 'You are currently at this venue!',
      steps: [
        {
          instruction: `You are already at ${from.name} (${from.building}${from.floor ? `, ${from.floor}` : ''}).`,
          landmark: from.building,
          distanceMeters: 0,
        },
      ],
      pathCoordinates: [{ x: from.x, y: from.y }],
      googleMapsUrl: FLAME_CAMPUS_CENTER.googleMapsUrl,
    };
  }

  // Intrabuilding special check (e.g. Charlies Cafe to APJ001 — both inside APJ #2!)
  const isSameBuilding = from.building === to.building || from.officialNumber === to.officialNumber;

  let totalMeters = 0;
  let hubResult: ShortestPathResult;

  if (isSameBuilding) {
    // Rooms within the same building (e.g. Charlies in APJ and APJ001)
    totalMeters = 25;
    hubResult = {
      totalMeters: 25,
      hubs: [from.hubNodeId],
      notes: [
        `Walk along the ${from.floor || 'ground floor'} corridor of ${from.building} directly toward ${to.name}.`,
      ],
    };
  } else {
    hubResult = findShortestPedestrianPath(from.hubNodeId, to.hubNodeId);
    // Add minor offset for leaving the start room and entering destination room
    totalMeters = hubResult.totalMeters + 30;
  }

  // Speed: ~75 meters/minute (standard student walking speed across campus)
  const walkTimeMinutes = Math.max(1, Math.round(totalMeters / 75));
  const stepsCount = Math.round(totalMeters * 1.35);

  // Contextual Pacing Description
  let paceDescription = 'Gentle 2 min campus walk';
  if (isSameBuilding) {
    paceDescription = '⚡ Under 1 min • Inside the same building!';
  } else if (walkTimeMinutes <= 2) {
    paceDescription = '⚡ Quick 1–2 min stroll • Nearby venue';
  } else if (walkTimeMinutes <= 4) {
    paceDescription = '🚶 Comfortable 3–4 min walk • Standard campus pace';
  } else {
    paceDescription = '🏃 Cross-campus 5–7 min walk • Head out now to make it on time!';
  }

  // Build step-by-step human directions (crisp and road-oriented)
  const steps: CampusRouteStep[] = [];

  // Step 1: Start
  steps.push({
    instruction: `Start at ${from.name} (${from.building}).`,
    landmark: from.building,
    distanceMeters: 15,
  });

  // Step 2...N: Waypoint instructions along designated paved roads
  if (hubResult.notes.length > 0) {
    const stepDistance = Math.round((totalMeters - 30) / Math.max(1, hubResult.notes.length));
    hubResult.notes.forEach((note) => {
      steps.push({
        instruction: note,
        distanceMeters: Math.max(20, stepDistance),
      });
    });
  } else if (isSameBuilding) {
    steps.push({
      instruction: `Both locations are inside ${from.building} (Building #${from.officialNumber || 2}). Follow indoor corridor signage to ${to.name}.`,
      distanceMeters: 25,
    });
  }

  // Final Step: Arrival
  steps.push({
    instruction: `Arrive at ${to.name} (${to.building}).`,
    landmark: to.name,
    distanceMeters: 15,
  });

  // Compile smooth path coordinates for SVG canvas drawing:
  const rawCoords: { x: number; y: number }[] = [];
  rawCoords.push({ x: from.x, y: from.y });

  hubResult.hubs.forEach((hId) => {
    const hub = CAMPUS_HUB_NODES[hId];
    if (hub) {
      rawCoords.push({ x: hub.x, y: hub.y });
    }
  });

  rawCoords.push({ x: to.x, y: to.y });

  // Filter consecutive duplicate coordinates
  const pathCoordinates: { x: number; y: number }[] = [];
  rawCoords.forEach((pt) => {
    const last = pathCoordinates[pathCoordinates.length - 1];
    if (!last || Math.abs(last.x - pt.x) > 0.5 || Math.abs(last.y - pt.y) > 0.5) {
      pathCoordinates.push(pt);
    }
  });

  // Direct Google Maps URL with walking mode
  const encodedDest = encodeURIComponent(`FLAME University ${to.name} ${to.building}`);
  const googleMapsUrl = `https://www.google.com/maps/dir/?api=1&destination=${encodedDest}&destination_place_id=ChIJ0Y9pjzO8wjsRPPv3jEiQuSY&travelmode=walking`;

  return {
    fromLocation: from,
    toLocation: to,
    distanceMeters: totalMeters,
    walkTimeMinutes,
    stepsCount,
    paceDescription,
    steps,
    pathCoordinates,
    googleMapsUrl,
  };
}
